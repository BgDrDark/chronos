def resolve_query_permission(field_name: str) -> str | None:
    """Return the permission required for a query field, or None if unknown."""
    if field_name in PUBLIC_QUERIES:
        return None
    if field_name in QUERY_PERMISSION_MAPPING:
        return QUERY_PERMISSION_MAPPING[field_name]

    lowered = field_name.lower()
    for prefix, permission in QUERY_PERMISSION_PREFIXES:
        if lowered.startswith(prefix):
            return permission
    return None
